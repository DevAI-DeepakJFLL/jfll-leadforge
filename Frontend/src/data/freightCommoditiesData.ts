/**
 * Helper to compile lowercased search haystack for a monthly commodity record
 */
export function compileSearchHaystack(r: {
  hubName: string;
  hubId: string;
  season: string;
  airExport: string;
  airImport: string;
  seaExport: string;
  seaImport: string;
  equipment: string;
  gateways: string;
  clusters: string;
  tradeLanes: string;
}): string {
  return [
    r.hubName,
    r.hubId,
    r.season,
    r.airExport,
    r.airImport,
    r.seaExport,
    r.seaImport,
    r.equipment,
    r.gateways,
    r.clusters,
    r.tradeLanes,
  ].join(' ').toLowerCase();
}

// Pre-compile searchHaystack on all 96 monthly commodity records
MONTHLY_COMMODITY_RECORDS.forEach(record => {
  record.searchHaystack = compileSearchHaystack(record);
});

/**
 * Pre-grouped month index for instant O(1) month lookup (months 1 - 12)
 */
export const MONTH_INDEX: Map<number, MonthlyRecord[]> = new Map();
for (let m = 1; m <= 12; m++) {
  MONTH_INDEX.set(m, []);
}
MONTHLY_COMMODITY_RECORDS.forEach(record => {
  const monthRecords = MONTH_INDEX.get(record.month);
  if (monthRecords) {
    monthRecords.push(record);
  } else {
    MONTH_INDEX.set(record.month, [record]);
  }
});

const ALL_GATEWAY_HUB_IDS: GatewayHubId[] = ['ALL', 'DEL', 'BOM', 'BLR', 'MAA', 'HYD', 'CCU', 'AMD', 'COK'];

/**
 * Pre-computed mapping from GatewayHubId to relevant ColdChainSpec[] for instant O(1) lookup
 */
export const HUB_COLD_CHAIN_MAP: Record<GatewayHubId, ColdChainSpec[]> = (() => {
  const map: Record<GatewayHubId, ColdChainSpec[]> = {
    ALL: COLD_CHAIN_SPECS,
    DEL: [],
    BOM: [],
    BLR: [],
    MAA: [],
    HYD: [],
    CCU: [],
    AMD: [],
    COK: [],
  };

  ALL_GATEWAY_HUB_IDS.forEach(hub => {
    if (hub === 'ALL') {
      map.ALL = COLD_CHAIN_SPECS;
      return;
    }
    const hubInfo = HUB_GATEWAYS[hub];
    if (!hubInfo) {
      map[hub] = [];
      return;
    }
    const searchName = hubInfo.name.toLowerCase();
    const searchCode = hub.toLowerCase();
    map[hub] = COLD_CHAIN_SPECS.filter(s => {
      const lowerHubs = s.hubs.toLowerCase();
      return lowerHubs.includes(searchName) || lowerHubs.includes(searchCode);
    });
  });

  return map;
})();

/**
 * Computes booking status ('active' | 'upcoming' | 'off-season') relative to a reference month.
 * Defaults to current month or active planning month (11 for November peak).
 */
export function getBookingStatus(
  recordMonth: number,
  activeMonth: number = 11
): BookingWindowStatus {
  if (recordMonth === activeMonth) return 'active';
  const diff = (recordMonth - activeMonth + 12) % 12;
  if (diff === 1) return 'upcoming';
  return 'off-season';
}

/**
 * Returns all monthly commodity records for a given month (1 to 12).
 * Utilizes MONTH_INDEX for instant O(1) lookup.
 */
export function getMonthlyRecordsByMonth(month: number): MonthlyRecord[] {
  if (month < 1 || month > 12) return [];
  return MONTH_INDEX.get(month) || [];
}

/**
 * Filters commodity records across month, hub, mode, and query strings.
 * Executes a single-pass composite filter over candidates indexed by month.
 * When a search query is active and allMonthsIfQuery is true (or month is outside 1-12),
 * searches across the full 96-record national calendar so sales reps can find commodities in any month.
 */
export function filterCommodityRecords(
  month: number,
  hub: GatewayHubId,
  mode?: string,
  query?: string,
  allMonthsIfQuery: boolean = false
): MonthlyRecord[] {
  const trimmedQuery = typeof query === 'string' ? query.trim().toLowerCase() : '';
  const checkQuery = trimmedQuery.length > 0;

  // When a query is entered and allMonthsIfQuery is enabled (or month is outside 1-12),
  // candidate pool expands to all 96 records so searching "Grapes" or "Mango" matches across all months.
  const useAllMonths = (allMonthsIfQuery && checkQuery) || month < 1 || month > 12;
  const candidates =
    (!useAllMonths ? MONTH_INDEX.get(month) : null) ||
    MONTHLY_COMMODITY_RECORDS;

  const checkHub = Boolean(hub && hub !== 'ALL');
  const checkMode = Boolean(mode && mode !== 'All' && mode !== 'All Modes');
  const lowerMode = checkMode ? mode!.toLowerCase() : '';

  // Single-pass composite filtering
  return candidates.filter(r => {
    // 1. Hub check
    if (checkHub && r.hubId !== hub) {
      return false;
    }

    // 2. Mode check
    if (checkMode) {
      if (lowerMode === 'air export' || lowerMode === 'air-export') {
        if (!r.airExport) return false;
      } else if (lowerMode === 'air import' || lowerMode === 'air-import') {
        if (!r.airImport) return false;
      } else if (lowerMode === 'sea export' || lowerMode === 'sea-export') {
        if (!r.seaExport) return false;
      } else if (lowerMode === 'sea import' || lowerMode === 'sea-import') {
        if (!r.seaImport) return false;
      } else if (lowerMode === 'air') {
        if (!r.airExport && !r.airImport) return false;
      } else if (lowerMode === 'sea') {
        if (!r.seaExport && !r.seaImport) return false;
      } else if (lowerMode === 'export') {
        if (!r.airExport && !r.seaExport) return false;
      } else if (lowerMode === 'import') {
        if (!r.airImport && !r.seaImport) return false;
      }
    }

    // 3. Query check against pre-compiled searchHaystack with smart plural & token matching
    if (checkQuery) {
      const haystack = r.searchHaystack ?? compileSearchHaystack(r);
      const q = trimmedQuery;
      let matched = haystack.includes(q);
      if (!matched && q.endsWith('es')) {
        matched = haystack.includes(q.slice(0, -2));
      }
      if (!matched && q.endsWith('s')) {
        matched = haystack.includes(q.slice(0, -1));
      }
      if (!matched && q.includes('automob')) {
        matched = haystack.includes('auto');
      }
      if (!matched) {
        const words = q.split(/\s+/).filter(w => w.length > 2);
        if (words.length > 1) {
          matched = words.every(w =>
            haystack.includes(w) ||
            (w.endsWith('s') && haystack.includes(w.slice(0, -1)))
          );
        }
      }
      if (!matched) {
        return false;
      }
    }

    return true;
  });
}

